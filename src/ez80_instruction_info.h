union ez80_flags {
	struct {
		uint8_t carry : 1;
		uint8_t addsub : 1;
		uint8_t three : 1;
		uint8_t half : 1;
		uint8_t five : 1;
		uint8_t overflow : 1;
		uint8_t zero : 1;
		uint8_t sign : 1;
	};
	uint8_t raw;
};

